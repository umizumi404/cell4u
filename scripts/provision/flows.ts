/* -------------------------------------------------------------------------- */

export function buildCallFlow(args: BuildArgs): FlowCreateParams {
  return {
    start_speaker: "agent",
    start_node_id: "ice_break",
    model_choice: {
      type: "cascading",
      // Fast model in the call loop per AGENTS.md "Model routing defaults".
      // Choices are constrained to Retell's enum; gpt-5-mini is the closest
      // match to the stated default. Override per-node for the objection
      // node in Ticket 6 if desired.
      model: "gpt-5-mini",
    },
    global_prompt: [
      "You are an outbound voice sales agent.",
      `Vertical: ${args.verticalId}.`,
      `Default persona archetype: ${args.defaultArchetype}.`,
      "Be concise. Never invent customer history. Never claim to be human.",
      "If the lead asks if you are an AI, say yes.",
      "Stop talking the moment the lead starts speaking.",
    ].join("\n"),
    nodes: callFlowNodes(args),
    tools: [
      reportStageChangeTool(args.toolWebhookUrl),
      logObjectionTool(args.toolWebhookUrl),
      bookMeetingTool(args.successEvent, args.toolWebhookUrl),
    ],
    default_dynamic_variables: {
      cell4u_marker: `cell4u/${args.verticalId}/call/v1`,
      persona_opener: "Hi — is this a good moment for a quick call?",
      persona_voice: "calm, direct, friendly",
      target_descriptor: "the lead's situation",
      seller_business_name: "your business",
      offer: "our service",
      win_cta: "a short follow-up call",
    },
  };
}

export function buildIntakeFlow(args: IntakeBuildArgs): FlowCreateParams {
  return {
    start_speaker: "agent",
    start_node_id: "ice_break",
    model_choice: {
      type: "cascading",
      model: "gpt-5-mini",
    },
    global_prompt: [
      "You are an intake agent for the Cell For You platform.",
      "Your job is to detect the user's vertical and collect the fields the chosen blueprint needs.",
      "Be brief, friendly, and confirm each answer before moving on.",
    ].join("\n"),
    nodes: intakeFlowNodes(),
    tools: [detectBlueprintTool(args.toolWebhookUrl)],
    default_dynamic_variables: {
      cell4u_marker: "cell4u/intake/v1",
    },
  };
}
